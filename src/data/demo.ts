/** `YYYY-MM-DD` for `n` days ago, so seeded day counters stay believable. */
function daysAgo(n: number): string {
  const date = new Date();
  date.setDate(date.getDate() - n);
  return date.toISOString().slice(0, 10);
}

function hoursAgo(n: number): string {
  return new Date(Date.now() - n * 3_600_000).toISOString();
}

function birthYearsAgo(years: number, month = 5, day = 14): string {
  return `${new Date().getFullYear() - years}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
}

